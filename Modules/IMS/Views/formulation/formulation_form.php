];

$v = static function (string $name, string $default = '') use ($formulation, $hasOldInput): string {
    if ($hasOldInput) {
        $value = old($name);
        return $value !== null ? (string) $value : '';
    }

    return (string) ($formulation[$name] ?? $default);
};

$err = static function (string $name) use ($validation): void {
    if (isset($validation[$name])) {
        echo '<small class="admin-error">' . esc($validation[$name]) . '</small>';
    }
};

$sectionTitle = static function (string $title): void {
    echo '<p style="font-weight:600;font-size:0.82em;text-transform:uppercase;letter-spacing:.07em;color:var(--text-muted,#6c757d);margin:0 0 14px 0;padding-bottom:8px;border-bottom:1px solid var(--border-color,#dee2e6);">' . esc($title) . '</p>';
};

$select = static function (string $name, mixed $value) use ($v): string {
    return (string) $v($name) === (string) $value ? 'selected' : '';
};

$preparedByDefault = $isEdit ? '' : (string) $currentUserId;
$preparedDateDefault = $isEdit ? '' : date('Y-m-d');
