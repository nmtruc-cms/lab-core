$hasOldInput = old('name') !== null;
$fmLang = static fn (string $key, array $args = []): string => lang('IMS.formulations.' . $key, $args);
$statusLabels = [
    'active' => $fmLang('status.active'),
    'approved' => $fmLang('status.approved'),
    'depleted' => $fmLang('status.depleted'),
    'expired' => $fmLang('status.expired'),
];
$typeLabels = [
    'Reagent mixture' => $fmLang('types.reagentMixture'),
